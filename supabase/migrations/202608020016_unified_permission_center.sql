create or replace function public.set_user_permission_grant(
  requested_subject_user_id uuid,
  requested_permission_key text,
  requested_tenant_id uuid default null,
  requested_enabled boolean default true
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  grant_id bigint;
  actor_id uuid := auth.uid();
begin
  if actor_id is null or not private.is_platform_owner() then
    raise exception '只有平台负责人可以修改统一权限';
  end if;

  if requested_permission_key not in (
    'standard_question_bank.manage',
    'conversation_practice.manage',
    'grade_center.manage',
    'learning_records.manage',
    'document_reviews.manage',
    'visa_management.manage'
  ) then
    raise exception '权限编号无效';
  end if;

  if requested_tenant_id is null then
    if requested_permission_key <> 'standard_question_bank.manage' then
      raise exception '该权限必须指定机构';
    end if;
    if not exists (
      select 1 from public.profiles as profile
      where profile.id = requested_subject_user_id
        and profile.global_role in ('platform_deputy', 'platform_admin')
        and coalesce(profile.status, 'active') = 'active'
    ) then
      raise exception '只能给正常的平台副负责人或平台管理员授权';
    end if;
  else
    if requested_permission_key = 'standard_question_bank.manage' then
      raise exception '标准题库权限只能在平台范围分配';
    end if;
    if not exists (
      select 1
      from public.tenant_memberships as membership
      join public.profiles as profile on profile.id = membership.user_id
      where membership.tenant_id = requested_tenant_id
        and membership.user_id = requested_subject_user_id
        and membership.role = 'admin'
        and membership.status = 'active'
        and coalesce(profile.status, 'active') = 'active'
    ) then
      raise exception '只能给当前机构状态正常的管理员授权';
    end if;
  end if;

  if requested_enabled then
    select permission_grant.id
      into grant_id
    from public.permission_grants as permission_grant
    where permission_grant.subject_user_id = requested_subject_user_id
      and permission_grant.permission_key = requested_permission_key
      and permission_grant.revoked_at is null
      and (
        (requested_tenant_id is null and permission_grant.scope_type = 'platform' and permission_grant.tenant_id is null)
        or (requested_tenant_id is not null and permission_grant.scope_type = 'tenant' and permission_grant.tenant_id = requested_tenant_id)
      )
    limit 1;

    if grant_id is null then
      insert into public.permission_grants (
        scope_type,
        tenant_id,
        subject_user_id,
        permission_key,
        granted_by
      ) values (
        case when requested_tenant_id is null then 'platform' else 'tenant' end,
        requested_tenant_id,
        requested_subject_user_id,
        requested_permission_key,
        actor_id
      ) returning id into grant_id;

      insert into public.permission_grant_audit_logs (
        permission_grant_id,
        actor_id,
        subject_user_id,
        tenant_id,
        permission_key,
        action
      ) values (
        grant_id,
        actor_id,
        requested_subject_user_id,
        requested_tenant_id,
        requested_permission_key,
        'granted'
      );
    end if;
  else
    update public.permission_grants
    set revoked_by = actor_id,
        revoked_at = now()
    where subject_user_id = requested_subject_user_id
      and permission_key = requested_permission_key
      and revoked_at is null
      and (
        (requested_tenant_id is null and scope_type = 'platform' and tenant_id is null)
        or (requested_tenant_id is not null and scope_type = 'tenant' and tenant_id = requested_tenant_id)
      )
    returning id into grant_id;

    if grant_id is not null then
      insert into public.permission_grant_audit_logs (
        permission_grant_id,
        actor_id,
        subject_user_id,
        tenant_id,
        permission_key,
        action
      ) values (
        grant_id,
        actor_id,
        requested_subject_user_id,
        requested_tenant_id,
        requested_permission_key,
        'revoked'
      );
    end if;
  end if;

  return grant_id;
end;
$$;

revoke all on function public.set_user_permission_grant(uuid, text, uuid, boolean) from public;
grant execute on function public.set_user_permission_grant(uuid, text, uuid, boolean) to authenticated;

-- Migrate every still-active grant into the unified table. Historical revoked
-- rows remain in the old tables and are not treated as active permissions.
do $$
declare
  mapping record;
begin
  for mapping in
    select * from (values
      ('conversation_practice_admin_assignments', 'conversation_practice.manage'),
      ('grade_center_admin_assignments', 'grade_center.manage'),
      ('learning_record_admin_assignments', 'learning_records.manage'),
      ('document_review_admin_assignments', 'document_reviews.manage'),
      ('visa_admin_assignments', 'visa_management.manage')
    ) as value(table_name, permission_key)
  loop
    if to_regclass('public.' || mapping.table_name) is not null then
      execute format(
        'insert into public.permission_grants (
           scope_type, tenant_id, subject_user_id, permission_key,
           granted_by, granted_at
         )
         select ''tenant'', tenant_id, admin_id, $1, granted_by, granted_at
         from public.%I as legacy
         where legacy.revoked_at is null
           and not exists (
             select 1 from public.permission_grants as existing
             where existing.scope_type = ''tenant''
               and existing.tenant_id = legacy.tenant_id
               and existing.subject_user_id = legacy.admin_id
               and existing.permission_key = $1
               and existing.revoked_at is null
           )',
        mapping.table_name
      ) using mapping.permission_key;
    end if;
  end loop;

  if to_regclass('public.question_bank_admin_assignments') is not null then
    insert into public.permission_grants (
      scope_type, tenant_id, subject_user_id, permission_key,
      granted_by, granted_at
    )
    select
      'platform', null, legacy.admin_id, 'standard_question_bank.manage',
      legacy.granted_by, legacy.granted_at
    from public.question_bank_admin_assignments as legacy
    where legacy.revoked_at is null
      and not exists (
        select 1 from public.permission_grants as existing
        where existing.scope_type = 'platform'
          and existing.tenant_id is null
          and existing.subject_user_id = legacy.admin_id
          and existing.permission_key = 'standard_question_bank.manage'
          and existing.revoked_at is null
      );
  end if;
end;
$$;

-- Retire every direct client-facing legacy assignment API. These historical
-- tables are frozen and no longer participate in any permission decision.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'conversation_practice_admin_assignments',
    'grade_center_admin_assignments',
    'learning_record_admin_assignments',
    'library_admin_assignments',
    'document_review_admin_assignments',
    'visa_admin_assignments',
    'question_bank_admin_assignments',
    'announcement_admin_assignments',
    'help_center_admin_assignments'
  ]
  loop
    if to_regclass('public.' || table_name) is not null then
      execute format('revoke all on public.%I from anon, authenticated', table_name);
    end if;
  end loop;
end;
$$;

