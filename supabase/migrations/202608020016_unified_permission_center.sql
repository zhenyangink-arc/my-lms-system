-- Unified permission center.
--
-- All application-level exception grants are stored in one auditable table.
-- Legacy per-module assignment tables are imported once and then frozen.
-- Application access and RLS helpers only read the unified grant table.

create table if not exists public.permission_grants (
  id bigint generated by default as identity primary key,
  scope_type text not null check (scope_type in ('platform', 'tenant')),
  tenant_id uuid references public.tenants(id) on delete cascade,
  subject_user_id uuid not null references public.profiles(id) on delete cascade,
  permission_key text not null check (permission_key in (
    'standard_question_bank.manage',
    'conversation_practice.manage',
    'grade_center.manage',
    'learning_records.manage',
    'document_reviews.manage',
    'visa_management.manage'
  )),
  granted_by uuid not null references public.profiles(id) on delete restrict,
  granted_at timestamptz not null default now(),
  revoked_by uuid references public.profiles(id) on delete set null,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  check (
    (scope_type = 'platform' and tenant_id is null)
    or (scope_type = 'tenant' and tenant_id is not null)
  ),
  check (
    (revoked_at is null and revoked_by is null)
    or (revoked_at is not null and revoked_by is not null)
  )
);

create unique index if not exists permission_grants_active_platform_idx
  on public.permission_grants (subject_user_id, permission_key)
  where scope_type = 'platform' and tenant_id is null and revoked_at is null;

create unique index if not exists permission_grants_active_tenant_idx
  on public.permission_grants (tenant_id, subject_user_id, permission_key)
  where scope_type = 'tenant' and revoked_at is null;

create index if not exists permission_grants_subject_idx
  on public.permission_grants (subject_user_id, tenant_id, permission_key, revoked_at);

create table if not exists public.permission_grant_audit_logs (
  id bigint generated by default as identity primary key,
  permission_grant_id bigint references public.permission_grants(id) on delete set null,
  actor_id uuid references public.profiles(id) on delete set null,
  subject_user_id uuid not null,
  tenant_id uuid,
  permission_key text not null,
  action text not null check (action in ('granted', 'revoked')),
  created_at timestamptz not null default now()
);

create index if not exists permission_grant_audit_logs_created_idx
  on public.permission_grant_audit_logs (created_at desc);

alter table public.permission_grants enable row level security;
alter table public.permission_grant_audit_logs enable row level security;

drop policy if exists "permission grants visible to authorized viewers"
  on public.permission_grants;
create policy "permission grants visible to authorized viewers"
on public.permission_grants for select to authenticated
using (
  subject_user_id = (select auth.uid())
  or (select private.is_platform_owner())
  or exists (
    select 1
    from public.tenant_memberships as membership
    where membership.user_id = (select auth.uid())
      and membership.tenant_id = permission_grants.tenant_id
      and membership.status = 'active'
      and membership.role in ('tenant_super_admin', 'ceo')
  )
);

drop policy if exists "permission audit visible to platform owner"
  on public.permission_grant_audit_logs;
create policy "permission audit visible to platform owner"
on public.permission_grant_audit_logs for select to authenticated
using ((select private.is_platform_owner()));

revoke all on public.permission_grants from anon, authenticated;
revoke all on public.permission_grant_audit_logs from anon, authenticated;
grant select on public.permission_grants to authenticated;
grant select on public.permission_grant_audit_logs to authenticated;

create or replace function private.current_user_has_explicit_permission(
  requested_permission_key text,
  requested_tenant_id uuid default null
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.permission_grants as permission_grant
    join public.profiles as profile
      on profile.id = permission_grant.subject_user_id
    where permission_grant.subject_user_id = (select auth.uid())
      and permission_grant.permission_key = requested_permission_key
      and permission_grant.revoked_at is null
      and coalesce(profile.status, 'active') = 'active'
      and (
        (requested_tenant_id is null
          and permission_grant.scope_type = 'platform'
          and permission_grant.tenant_id is null)
        or
        (requested_tenant_id is not null
          and permission_grant.scope_type = 'tenant'
          and permission_grant.tenant_id = requested_tenant_id)
      )
  );
$$;

revoke all on function private.current_user_has_explicit_permission(text, uuid) from public;
grant execute on function private.current_user_has_explicit_permission(text, uuid) to authenticated;

